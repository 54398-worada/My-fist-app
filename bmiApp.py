import streamlit as st

# หัวข้อแอปพลิเคชัน
st.title("🏋️ แอปพลิเคชันคำนวณค่าดัชนีมวลกาย (BMI)")

# รับค่าน้ำหนักและส่วนสูงจากผู้ใช้
weight = st.number_input("กรุณากรอกน้ำหนัก (กิโลกรัม):", min_value=1.0, value=55.0)
height_cm = st.number_input("กรุณากรอกส่วนสูง (เซนติเมตร):", min_value=1.0, value=158.0)

if st.button("🧮 คำนวณค่า BMI"):
    # แปลงส่วนสูงจากเซนติเมตรเป็นเมตร
    height_m = height_cm / 100
    
    # คำนวณค่า BMI (น้ำหนัก / ส่วนสูงเมตร^2)
    bmi = weight / (height_m ** 2)
    
    # แสดงผลค่า BMI
    st.write(f"### ค่า BMI ของคุณคือ: **{bmi:.2f}**")
    
    # การแปลผลตามเกณฑ์เงื่อนไข if-elif-else
    # โค้ดบรรทัดด้านล่างย่อหน้าต้องเว้นช่องว่าง (Indent) ข้างหน้าตามเงื่อนไข
    if bmi < 18.5:
        st.warning("⚠️ อยู่ในเกณฑ์: น้ำหนักน้อย / ผอม")
    elif 18.5 <= bmi < 23.0:
        st.success("✅ อยู่ในเกณฑ์: ปกติ (สุขภาพดี)")
    elif 23.0 <= bmi < 25.0:
        st.info("ℹ️ อยู่ในเกณฑ์: ท้วม / น้ำหนักเกิน")
    elif 25.0 <= bmi < 30.0:
        st.warning("⚠️ อยู่ในเกณฑ์: อ้วน / อ้วนระดับ 1")
    else:
        st.error("🚨 อยู่ในเกณฑ์: อ้วนมาก / อ้วนระดับ 2")
